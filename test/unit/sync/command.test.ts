import { describe, expect, it } from 'vitest';
import { toWorkspaceEditSpec } from '../../../src/sync/editSpec';
import { chooseText, hasGeneratedHeader, resolveRootNamespace, syncFileInput, syncItemRole } from '../../../src/sync/candidates';
import type { SyncPlan } from '../../../src/sync/plan';

const plan = (path: string, edits: { start: number; end: number; newText: string; kind?: 'declaration' | 'using' | 'qualified' }[]): SyncPlan =>
  ({ edits: new Map([[path, edits.map((e) => ({ kind: 'using' as const, ...e }))]]), skipped: [], moves: [], ambiguous: [] });

describe('toWorkspaceEditSpec', () => {
  it('maps offsets in CRLF+BOM text to positions', () => {
    const text = '﻿using A;\r\nnamespace Old;\r\nclass C {}';
    const at = text.indexOf('Old');
    const spec = toWorkspaceEditSpec(plan('/a.cs', [{ start: at, end: at + 3, newText: 'New' }]), new Map([['/a.cs', text]]));
    expect(spec[0].range).toEqual({ startLine: 1, startCol: 10, endLine: 1, endCol: 13 });
  });
  it('does not count the BOM as a column on line 0', () => {
    const text = '﻿using A;\r\nclass C {}';
    const spec = toWorkspaceEditSpec(plan('/a.cs', [{ start: 1, end: 1, newText: 'using B;\r\n' }]), new Map([['/a.cs', text]]));
    expect(spec[0].range).toEqual({ startLine: 0, startCol: 0, endLine: 0, endCol: 0 });
  });
  it('leaves BOM-less text (open document) untouched', () => {
    const text = 'using A;\nnamespace Old;';
    const at = text.indexOf('Old');
    const spec = toWorkspaceEditSpec(plan('/a.cs', [{ start: 0, end: 5, newText: 'x' }, { start: at, end: at + 3, newText: 'N' }]), new Map([['/a.cs', text]]));
    expect(spec[0].range.startCol).toBe(0);
    expect(spec[1].range).toEqual({ startLine: 1, startCol: 10, endLine: 1, endCol: 13 });
  });
  it('labels per edit kind', () => {
    const text = 'using Old;\nnamespace Old;\nclass C { Old.T x; }';
    const o = (s: string, from = 0) => text.indexOf(s, from);
    const spec = toWorkspaceEditSpec(plan('/a.cs', [
      { start: o('Old'), end: o('Old') + 3, newText: 'New', kind: 'using' },
      { start: o('Old', 12), end: o('Old', 12) + 3, newText: 'New', kind: 'declaration' },
      { start: o('Old.T'), end: o('Old.T') + 5, newText: 'New.T', kind: 'qualified' },
      { start: 0, end: 0, newText: 'using Z;\n', kind: 'using' },
    ]), new Map([['/a.cs', text]]));
    expect(spec.map((s) => s.kind)).toEqual(['using', 'declaration', 'qualified', 'using']);
  });
});

describe('syncItemRole', () => {
  const dir = '/p';
  it('plain .cs files are source', () => expect(syncItemRole(dir, { fullPath: '/p/src/A.cs' })).toBe('source'));
  it('excludes linked, outside, bin/obj, non-cs', () => {
    expect(syncItemRole(dir, { fullPath: '/p/A.cs', link: 'A.cs' })).toBe('excluded');
    expect(syncItemRole(dir, { fullPath: '/q/A.cs' })).toBe('excluded');
    expect(syncItemRole(dir, { fullPath: '/p/obj/Debug/A.cs' })).toBe('excluded');
    expect(syncItemRole(dir, { fullPath: '/p/a/bin/A.cs' })).toBe('excluded');
    expect(syncItemRole(dir, { fullPath: '/p/A.txt' })).toBe('excluded');
  });
  it('generated file names are generated, case-insensitively', () => {
    for (const n of ['A.g.cs', 'A.g.i.cs', 'Form1.Designer.cs', 'B.DESIGNER.CS']) expect(syncItemRole(dir, { fullPath: `/p/${n}` }), n).toBe('generated');
  });
  it('generated names under obj/ or bin/, linked or outside stay excluded', () => {
    expect(syncItemRole(dir, { fullPath: '/p/obj/Debug/net8.0/A.g.cs' })).toBe('excluded');
    expect(syncItemRole(dir, { fullPath: '/p/bin/X.Designer.cs' })).toBe('excluded');
    expect(syncItemRole(dir, { fullPath: '/p/A.g.cs', link: 'A.g.cs' })).toBe('excluded');
    expect(syncItemRole(dir, { fullPath: '/q/A.g.cs' })).toBe('excluded');
  });
});

describe('syncFileInput', () => {
  const base = { path: '/p/A.cs', projectDir: '/p', rootNamespace: 'R', inScope: true };
  it('a source file keeps its scope', () => {
    expect(syncFileInput('source', { ...base, text: 'class C {}' })).toEqual({ file: { ...base, text: 'class C {}' }, generated: false });
  });
  it('a generated name or an auto-generated header goes in out of scope', () => {
    expect(syncFileInput('generated', { ...base, text: 'class C {}' })).toEqual({ file: { ...base, text: 'class C {}', inScope: false }, generated: true });
    const text = '// <auto-generated>\nnamespace Old;';
    expect(syncFileInput('source', { ...base, text })).toEqual({ file: { ...base, text, inScope: false }, generated: true });
  });
  it('a generated file in an out-of-scope project is not reported', () => {
    expect(syncFileInput('generated', { ...base, text: '', inScope: false }).generated).toBe(false);
  });
});

describe('resolveRootNamespace', () => {
  it('uses the evaluated value', () => expect(resolveRootNamespace('/p/My.App.csproj', 'Company.My.App')).toBe('Company.My.App'));
  it('falls back to the project file name when empty or missing', () => {
    expect(resolveRootNamespace('/p/My.App.csproj', '  ')).toBe('My.App');
    expect(resolveRootNamespace('/p/My.App.CSPROJ', undefined)).toBe('My.App');
  });
});

describe('generated headers and dirty text', () => {
  it('detects <auto-generated in the first 5 lines only', () => {
    expect(hasGeneratedHeader('// <auto-generated>\nclass C {}')).toBe(true);
    expect(hasGeneratedHeader('a\nb\nc\nd\ne\n// <auto-generated>')).toBe(false);
    expect(hasGeneratedHeader('class C {}')).toBe(false);
  });
  it('prefers dirty document text over disk', async () => {
    expect(await chooseText('dirty', async () => 'disk')).toBe('dirty');
    expect(await chooseText(undefined, async () => 'disk')).toBe('disk');
  });
});
